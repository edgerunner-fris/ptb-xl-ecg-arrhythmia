"""M6: aggregate every measured number into one master table.

Nothing is recomputed here and nothing is typed by hand: every value is read
from results/*.json, which were written by the stage scripts. The point is that
README / experiment log / resume text can cite one auditable file.

Writes results/m6_master_table.json and docs/RESULTS_TABLE.md.

Usage: python src/m6_master_table.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
DOCS = ROOT / "docs"


def load(name):
    p = RESULTS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def masked(tag):
    d = load(f"{tag}_masked.json")
    if d is None:
        return None
    out = {}
    for split in ("val", "test"):
        out[split] = {}
        for head in ("super", "rhythm"):
            t = d["splits"][split][head]
            out[split][head] = {
                "macro_auc": t["metrics"]["macro_auc"],
                "macro_f1": t["metrics"]["macro_f1_at_0.5"],
                "min10_auc": t["stable_min10"]["macro_auc"],
                "min20_auc": t["stable_min20"]["macro_auc"],
                "n_scored": t["n_scored"],
            }
    return out


def model_row(tag):
    d = load(f"{tag}.json")
    if d is None:
        return None
    cfg = d.get("config", {})
    row = {
        "tag": tag,
        "params": cfg.get("params") or cfg.get("params_student"),
        "best_epoch": d.get("best_epoch"),
        "elapsed_sec": d.get("elapsed_sec"),
        "unmasked_test": {h: {"macro_auc": d["test"][h]["macro_auc"],
                              "macro_f1": d["test"][h]["macro_f1_at_0.5"]}
                          for h in ("super", "rhythm")},
    }
    if tag == "m5_kd_student":
        row["params_teacher"] = cfg.get("params_teacher")
        row["kd_weight"] = cfg.get("kd_weight")
    row["masked"] = masked(tag)
    return row


def main() -> int:
    DOCS.mkdir(exist_ok=True)
    out = {"source": "generated by src/m6_master_table.py from results/*.json",
           "note": "all values are copied from saved runs; none are estimates"}

    d0 = load("m0_data_report.json")
    out["data"] = {
        "dataset": d0["dataset"],
        "records_total": d0["integrity"]["csv_rows"],
        "patients_total": d0["integrity"]["unique_patient_id"],
        "protocol": d0["split"]["protocol"],
        "patient_intersection": d0["split"]["patient_intersection"],
        "patients_in_multiple_folds": d0["split"]["patients_with_multiple_folds"],
        "splits": {k: {"records": v["records"], "patients": v["patients"],
                       "super_positive": v["super_positive"],
                       "rhythm_positive": v["rhythm_positive"]}
                   for k, v in d0["split"]["splits"].items()},
        "signal_check": {k: d0["signals"][k] for k in
                         ("n_lead_order_variants", "fs_not_100", "length_not_1000",
                          "n_signals_not_12", "read_errors")},
    }

    out["models"] = {}
    for tag in ("m1_resnet", "m2_transformer", "m2_transformer_wide", "m5_kd_student"):
        r = model_row(tag)
        if r:
            out["models"][tag] = r

    # Differences cited in the docs are computed here from the stored metrics,
    # so they are auditable rather than hand arithmetic.
    def t(tag, head):
        return out["models"][tag]["masked"]["test"][head]["macro_auc"]

    if {"m1_resnet", "m2_transformer", "m2_transformer_wide", "m5_kd_student"} <= set(out["models"]):
        out["derived"] = {
            "resnet_minus_transformer_super_auc": t("m1_resnet", "super") - t("m2_transformer", "super"),
            "resnet_minus_transformer_rhythm_auc": t("m1_resnet", "rhythm") - t("m2_transformer", "rhythm"),
            "wide_minus_transformer_rhythm_auc": t("m2_transformer_wide", "rhythm") - t("m2_transformer", "rhythm"),
            "teacher_minus_kd_super_auc": t("m1_resnet", "super") - t("m5_kd_student", "super"),
            "teacher_minus_kd_rhythm_auc": t("m1_resnet", "rhythm") - t("m5_kd_student", "rhythm"),
            "teacher_minus_wide_rhythm_auc": t("m1_resnet", "rhythm") - t("m2_transformer_wide", "rhythm"),
            "kd_minus_transformer_super_auc": t("m5_kd_student", "super") - t("m2_transformer", "super"),
            "kd_minus_transformer_rhythm_auc": t("m5_kd_student", "rhythm") - t("m2_transformer", "rhythm"),
            "kd_param_ratio_to_teacher": (out["models"]["m5_kd_student"]["params"]
                                          / out["models"]["m5_kd_student"]["params_teacher"]),
        }

    out["ssl"] = {}
    for tag in ("m3_ssl_msm", "m3_ssl_joint"):
        d = load(f"{tag}.json")
        if d:
            last = d["history"][-1]
            out["ssl"][tag] = {
                "params_encoder": d["config"]["params_encoder"],
                "params_ssl_model": d["config"]["params_ssl_model"],
                "epochs": d["config"]["epochs"],
                "elapsed_sec": d["elapsed_sec"],
                "final_msm_mse": last["msm_mse"],
                "final_cl_loss": last["cl_loss"],
                "actual_mask_ratio": last["actual_mask_ratio"],
            }

    s = load("m3_summary.json")
    out["m3"] = {"curve": {}, "paired_delta_seed42": s["paired_delta_joint_minus_scratch"],
                 "modes": {}}
    for k, rows in s["curve"].items():
        out["m3"]["curve"][k] = [
            None if r is None else {
                "fraction": r["fraction"], "n_records": r["n_train_records"],
                "super_auc": r["test_super_auc"], "rhythm_auc": r["test_rhythm_auc"],
                "super_f1": r["test_super_f1"], "rhythm_f1": r["test_rhythm_f1"],
            } for r in rows]
    for k, r in s["mode_comparison"].items():
        out["m3"]["modes"][k] = {"super_auc": r["test_super_auc"],
                                 "rhythm_auc": r["test_rhythm_auc"],
                                 "super_f1": r["test_super_f1"],
                                 "rhythm_f1": r["test_rhythm_f1"]}
    seed = load("m3_seed_check.json")
    if seed:
        out["m3"]["seed_check"] = seed["points"]
    jf = out["m3"]["curve"]["joint_full"]
    if len(jf) > 2 and jf[1] and jf[2]:
        out.setdefault("derived", {})["m3_joint_5_to_10_rhythm_dip"] = (
            jf[1]["rhythm_auc"] - jf[2]["rhythm_auc"])

    cal = load("m4_calibration.json")
    out["m4"] = {"tag": cal["tag"], "fit_split": cal["fit_split"],
                 "eval_split": cal["eval_split"], "n_bins": cal["n_bins"],
                 "calibration": {}, "conformal": {}}
    for h, v in cal["heads"].items():
        out["m4"]["calibration"][h] = {
            "temperature": v["temperature"],
            "ece_pooled_before": v["ece_pooled_before"],
            "ece_pooled_after": v["ece_pooled_after"],
            "ece_mean_per_class_before": v["ece_mean_per_class_before"],
            "ece_mean_per_class_after": v["ece_mean_per_class_after"],
            "nll_before": v["nll_before"], "nll_after": v["nll_after"],
            "brier_before": v["brier_before"], "brier_after": v["brier_after"],
            "macro_auc_before": v["macro_auc_before"],
            "macro_auc_after": v["macro_auc_after"],
            "max_abs_auc_change": v["max_abs_auc_change"],
            "n_test_scored": v["n_test_scored"],
        }
    conf = load("m4_conformal.json")
    for h, v in conf["heads"].items():
        prim = v["primary"]
        mon = v["mondrian_primary"]
        out["m4"]["conformal"][h] = {
            "alpha": prim["alpha"],
            "marginal": {k: prim[k] for k in
                         ("marginal_coverage_mean_per_class", "marginal_coverage_min_class",
                          "pooled_coverage", "joint_coverage_all_classes",
                          "mean_positive_set_size", "mean_total_labels",
                          "mean_empty_sets_per_record", "mean_both_labels_per_record",
                          "mean_singleton_sets_per_record", "record_has_empty_set",
                          "n_test")},
            "positive_recall_marginal": {
                c: d["coverage_pos"] for c, d in prim["per_class"].items()},
            "positive_recall_marginal_mean": sum(
                d["coverage_pos"] for d in prim["per_class"].values()) / len(prim["per_class"]),
            "mondrian": {k: mon[k] for k in
                         ("positive_coverage_mean_per_class", "positive_coverage_min_class",
                          "negative_coverage_mean_per_class", "negative_coverage_min_class",
                          "pooled_coverage", "joint_coverage_all_classes",
                          "mean_positive_set_size", "mean_total_labels",
                          "mean_empty_sets_per_record", "mean_both_labels_per_record",
                          "mean_singleton_sets_per_record", "degenerate_classes")},
            "curve": [{"alpha": c["alpha"],
                       "marginal_coverage_mean_per_class": c["marginal_coverage_mean_per_class"],
                       "marginal_coverage_min_class": c["marginal_coverage_min_class"],
                       "pooled_coverage": c["pooled_coverage"],
                       "joint_coverage_all_classes": c["joint_coverage_all_classes"],
                       "mean_positive_set_size": c["mean_positive_set_size"],
                       "mean_total_labels": c["mean_total_labels"]}
                      for c in v["curve"]],
            "positive_confidence_shift": v["positive_confidence_shift"],
        }

    q = load("m5_quantize.json")
    if q:
        out["m5_quantize"] = {
            "params": q["fp32"]["params"],
            "fp32_size_bytes": q["fp32"]["size_bytes"],
            "int8_size_bytes": q["int8_dynamic"]["size_bytes"],
            "quantized_linear_modules": q["quantized_linear_modules"],
            "threads": q["threads"],
            "latency": {bs: {"fp32_median_ms": q["fp32"][f"latency_batch{bs}"]["median_ms"],
                             "int8_median_ms": q["int8_dynamic"][f"latency_batch{bs}"]["median_ms"],
                             "fp32_p95_ms": q["fp32"][f"latency_batch{bs}"]["p95_ms"],
                             "int8_p95_ms": q["int8_dynamic"][f"latency_batch{bs}"]["p95_ms"]}
                        for bs in (1, 32)},
            "test_macro_auc": {h: {"fp32": q["fp32"]["test"][h]["macro_auc"],
                                   "int8": q["int8_dynamic"]["test"][h]["macro_auc"]}
                               for h in ("super", "rhythm")},
            "test_macro_f1": {h: {"fp32": q["fp32"]["test"][h]["macro_f1_at_0.5"],
                                  "int8": q["int8_dynamic"]["test"][h]["macro_f1_at_0.5"]}
                              for h in ("super", "rhythm")},
        }

    att = load("m5_attention.json")
    if att:
        ss = att["samples"]
        out["m5_attention"] = {
            "tag": att["tag"], "method": att["method"], "caveat": att["caveat"],
            "n_correct": att["n_correct"], "n_wrong": att["n_wrong"],
            "mean_attention_top10pct_mass": sum(s["top10pct_mass"] for s in ss) / len(ss),
            "mean_grad_top10pct_mass": sum(s["grad_top10pct_mass"] for s in ss) / len(ss),
            "uniform_top10pct_mass": 0.10,
            "samples": [{"ecg_id": s["ecg_id"], "correct": s["correct"],
                         "true_set": s["true_set"], "pred_set": s["pred_set"],
                         "attention_peak_s": s["attention_peak_s"],
                         "top10pct_mass": s["top10pct_mass"],
                         "grad_top10pct_mass": s["grad_top10pct_mass"]} for s in ss],
        }
    sal = load("m5_saliency.json")
    if sal:
        ss = sal["samples"]
        out["m5_saliency"] = {
            "tag": sal["tag"], "method": sal["method"],
            "n_correct": sal["n_correct"], "n_wrong": sal["n_wrong"],
            "uniform_top10pct_mass": sal["uniform_top10pct_mass"],
            "mean_top10pct_mass": sum(s["top10pct_mass"] for s in ss) / len(ss),
            "samples": [{"ecg_id": s["ecg_id"], "correct": s["correct"],
                         "true_set": s["true_set"], "pred_set": s["pred_set"],
                         "explained_class": s["explained_class"],
                         "top10pct_mass": s["top10pct_mass"]} for s in ss],
        }

    (RESULTS / "m6_master_table.json").write_text(
        json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")

    # ---- markdown -------------------------------------------------------
    L = []
    a = L.append
    a("# Measured results (generated)\n")
    a("Generated by `src/m6_master_table.py` from `results/*.json`. "
      "Do not edit by hand; re-run the script.\n")
    a("## Data\n")
    a(f"- {out['data']['dataset']}, {out['data']['records_total']} records, "
      f"{out['data']['patients_total']} patients")
    a(f"- {out['data']['protocol']}; patient intersections "
      f"{out['data']['patient_intersection']}")
    for k, v in out["data"]["splits"].items():
        a(f"- {k}: {v['records']} records / {v['patients']} patients")
    a("")
    a("## Supervised models (statement-masked test)\n")
    a("| tag | params | best epoch | super AUC | super F1 | rhythm AUC | rhythm F1 | "
      "super AUC (min10) | rhythm AUC (min20) |")
    a("|---|---|---|---|---|---|---|---|---|")
    for t, r in out["models"].items():
        m = r["masked"]["test"]
        a(f"| {t} | {r['params']:,} | {r['best_epoch']} | {m['super']['macro_auc']:.4f} | "
          f"{m['super']['macro_f1']:.4f} | {m['rhythm']['macro_auc']:.4f} | "
          f"{m['rhythm']['macro_f1']:.4f} | {m['super']['min10_auc']:.4f} | "
          f"{m['rhythm']['min20_auc']:.4f} |")
    a("")
    a("## Self-supervised pretraining\n")
    a("| run | encoder params | epochs | final MSM MSE | final CL loss | mask ratio |")
    a("|---|---|---|---|---|---|")
    for t, r in out["ssl"].items():
        cl = "n/a" if r["final_cl_loss"] is None else f"{r['final_cl_loss']:.4f}"
        a(f"| {t} | {r['params_encoder']:,} | {r['epochs']} | {r['final_msm_mse']:.4f} | "
          f"{cl} | {r['actual_mask_ratio']:.4f} |")
    a("")
    a("## M3 label-fraction curve (test, statement-masked)\n")
    a("| fraction | n train records | joint super | joint rhythm | scratch super | "
      "scratch rhythm | MSM super | MSM rhythm |")
    a("|---|---|---|---|---|---|---|---|")
    rows = out["m3"]["curve"]
    for i, f in enumerate(rows["joint_full"]):
        def cell(init, key):
            r = rows[f"{init}_full"][i]
            return "n/a" if r is None else f"{r[key]:.4f}"
        a(f"| {f['fraction']*100:.0f}% | {f['n_records']} | {cell('joint','super_auc')} | "
          f"{cell('joint','rhythm_auc')} | {cell('scratch','super_auc')} | "
          f"{cell('scratch','rhythm_auc')} | {cell('msm','super_auc')} | "
          f"{cell('msm','rhythm_auc')} |")
    a("")
    a("## M3 adaptation modes (test, statement-masked)\n")
    a("| run | super AUC | rhythm AUC |")
    a("|---|---|---|")
    for k, r in out["m3"]["modes"].items():
        a(f"| {k} | {r['super_auc']:.4f} | {r['rhythm_auc']:.4f} |")
    a("")
    a("## M3 seed check (paired deltas)\n")
    a("| fraction | seed | joint-scratch super | joint-scratch rhythm | "
      "joint-MSM super | joint-MSM rhythm |")
    a("|---|---|---|---|---|---|")
    for f, seeds in out["m3"]["seed_check"].items():
        for sd, d in seeds.items():
            jm = d["delta"]["joint_minus_scratch"]
            jj = d["delta"].get("joint_minus_msm")
            mj = "n/a" if jj is None else f"{jj['super_auc']:+.4f}"
            mr = "n/a" if jj is None else f"{jj['rhythm_auc']:+.4f}"
            a(f"| {float(f)*100:.0f}% | {sd} | {jm['super_auc']:+.4f} | "
              f"{jm['rhythm_auc']:+.4f} | {mj} | {mr} |")
    a("")
    if "derived" in out:
        a("## Derived differences (computed from the rows above)\n")
        a("| quantity | value |")
        a("|---|---|")
        for k, v in out["derived"].items():
            a(f"| {k} | {v:.4f} |" if "ratio" in k else f"| {k} | {v:+.4f} |")
        a("")
    a("## M4 calibration (val-fit, test-evaluated, statement-masked)\n")
    a("| head | T | ECE pooled before | ECE pooled after | NLL before | NLL after | "
      "Brier before | Brier after | max |dAUC| |")
    a("|---|---|---|---|---|---|---|---|---|")
    for h, r in out["m4"]["calibration"].items():
        a(f"| {h} | {r['temperature']:.4f} | {r['ece_pooled_before']:.4f} | "
          f"{r['ece_pooled_after']:.4f} | {r['nll_before']:.4f} | {r['nll_after']:.4f} | "
          f"{r['brier_before']:.4f} | {r['brier_after']:.4f} | "
          f"{r['max_abs_auc_change']:.4f} |")
    a("")
    a("## M4 conformal (alpha = 0.1, nominal coverage 0.9)\n")
    a("| head | method | coverage | min class coverage | joint coverage | positive recall | "
      "set size (pos) | total labels | empty sets/record |")
    a("|---|---|---|---|---|---|---|---|---|")
    for h, r in out["m4"]["conformal"].items():
        m = r["marginal"]
        a(f"| {h} | marginal | {m['marginal_coverage_mean_per_class']:.4f} | "
          f"{m['marginal_coverage_min_class']:.4f} | {m['joint_coverage_all_classes']:.4f} | "
          f"{r['positive_recall_marginal_mean']:.4f} | {m['mean_positive_set_size']:.4f} | "
          f"{m['mean_total_labels']:.4f} | {m['mean_empty_sets_per_record']:.4f} |")
        w = r["mondrian"]
        a(f"| {h} | Mondrian | {w['pooled_coverage']:.4f} | "
          f"{w['positive_coverage_min_class']:.4f} (pos) | "
          f"{w['joint_coverage_all_classes']:.4f} | "
          f"{w['positive_coverage_mean_per_class']:.4f} | {w['mean_positive_set_size']:.4f} | "
          f"{w['mean_total_labels']:.4f} | {w['mean_empty_sets_per_record']:.4f} |")
    a("")
    a(f"Mondrian degenerate classes (n_pos_cal < 9): "
      f"super = {out['m4']['conformal']['super']['mondrian']['degenerate_classes']}; "
      f"rhythm = {out['m4']['conformal']['rhythm']['mondrian']['degenerate_classes']}.\n")
    a("## M5 quantization (CPU, 1 thread)\n")
    q = out["m5_quantize"]
    a(f"- state_dict: {q['fp32_size_bytes']/1e6:.2f} MB -> {q['int8_size_bytes']/1e6:.2f} MB "
      f"({q['fp32_size_bytes']/q['int8_size_bytes']:.2f}x smaller), "
      f"{q['quantized_linear_modules']} Linear modules quantized")
    for bs, v in q["latency"].items():
        a(f"- batch {bs}: {v['fp32_median_ms']:.2f} ms -> {v['int8_median_ms']:.2f} ms "
          f"(p95 {v['fp32_p95_ms']:.2f} -> {v['int8_p95_ms']:.2f})")
    for h, v in q["test_macro_auc"].items():
        a(f"- {h} macro-AUC {v['fp32']:.4f} -> {v['int8']:.4f}")
    a("")
    a("## M5 attribution\n")
    at = out["m5_attention"]
    a(f"- attention rollout, {at['n_correct']} correct + {at['n_wrong']} wrong samples: "
      f"mean top-10% mass {at['mean_attention_top10pct_mass']:.4f} "
      f"(uniform = 0.10); gradientxinput on the same samples "
      f"{at['mean_grad_top10pct_mass']:.4f}")
    sa = out["m5_saliency"]
    a(f"- ResNet gradientxinput, {sa['n_correct']} correct + {sa['n_wrong']} wrong: "
      f"mean top-10% mass {sa['mean_top10pct_mass']:.4f}")
    (DOCS / "RESULTS_TABLE.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", RESULTS / "m6_master_table.json", DOCS / "RESULTS_TABLE.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
